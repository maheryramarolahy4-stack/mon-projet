import { Router } from 'express';
import { register, login, googleLogin, me, updateMe } from '../controllers/authController.js';
import { listWallets, createWallet, updateWallet, deleteWallet } from '../controllers/walletController.js';
import { listTransactions, createTransaction, updateTransaction, deleteTransaction } from '../controllers/transactionController.js';
import { dashboard } from '../controllers/dashboardController.js';
import { categories, listBudgets, createBudget, updateBudget, deleteBudget, listSavings, createSaving, updateSaving, deleteSaving, addContribution, listDebts, createDebt, updateDebt, deleteDebt, addRepayment, listTransfers, createTransfer } from '../controllers/genericController.js';
import { requireAuth } from '../middleware/auth.js';

const router = Router();
router.post('/auth/register', register);
router.post('/auth/login', login);
router.post('/auth/google', googleLogin);
router.get('/auth/me', requireAuth, me);
router.patch('/auth/me', requireAuth, updateMe);
router.get('/dashboard', requireAuth, dashboard);
router.get('/wallets', requireAuth, listWallets);
router.post('/wallets', requireAuth, createWallet);
router.put('/wallets/:id', requireAuth, updateWallet);
router.delete('/wallets/:id', requireAuth, deleteWallet);
router.get('/transactions', requireAuth, listTransactions);
router.post('/transactions', requireAuth, createTransaction);
router.put('/transactions/:id', requireAuth, updateTransaction);
router.delete('/transactions/:id', requireAuth, deleteTransaction);
router.get('/categories', requireAuth, categories);
router.get('/budgets', requireAuth, listBudgets);
router.post('/budgets', requireAuth, createBudget);
router.put('/budgets/:id', requireAuth, updateBudget);
router.delete('/budgets/:id', requireAuth, deleteBudget);
router.get('/savings', requireAuth, listSavings);
router.post('/savings', requireAuth, createSaving);
router.put('/savings/:id', requireAuth, updateSaving);
router.delete('/savings/:id', requireAuth, deleteSaving);
router.post('/savings/:id/contributions', requireAuth, addContribution);
router.get('/debts', requireAuth, listDebts);
router.post('/debts', requireAuth, createDebt);
router.put('/debts/:id', requireAuth, updateDebt);
router.delete('/debts/:id', requireAuth, deleteDebt);
router.post('/debts/:id/repayments', requireAuth, addRepayment);
router.get('/transfers', requireAuth, listTransfers);
router.post('/transfers', requireAuth, createTransfer);
export default router;
